export function translate(language: Language, message: string, values: Record<string, string | number> = {}): string {
  const timeout = /^(.*) took too long\. Try again or choose a smaller EPUB\.$/.exec(message);
  if (timeout && timeout[1] !== '{operation}') return translate(language, '{operation} took too long. Try again or choose a smaller EPUB.', { operation: translate(language, timeout[1]) });
  const text = language === 'zh-CN' && Object.hasOwn(chinese, message) ? chinese[message] : message;
  return text.replace(/\{(\w+)\}/g, (placeholder, name: string) => Object.hasOwn(values, name) ? String(values[name]) : placeholder);
}
